"""Finite real model + audio WebSocket acceptance. Input is synthetic, not a mic."""
import argparse,asyncio,base64,hashlib,json,pathlib,socket,sys,time,wave
import numpy as np
from scipy.signal import resample_poly
from aiohttp import ClientSession,web,WSMsgType
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]))
from run import launch,shutdown
from voice.engine import VoiceEngine
from voice.server import make_app

def write_wav(path,pcm,rate):
    with wave.open(str(path),'wb') as f:f.setnchannels(1);f.setsampwidth(2);f.setframerate(rate);f.writeframes(pcm)

async def benchmark(args):
    out=pathlib.Path(args.output);out.mkdir(parents=True,exist_ok=True)
    with socket.socket() as s:s.bind(('127.0.0.1',0));port=s.getsockname()[1]
    proc,model,lock,log=launch(args.model_root,port);runner=None
    try:
        engine=VoiceEngine(args.voice_root,model.url,model.key)
        engine.warmup()
        question='曙光，我今天很累，想找你聊聊天。'
        audio,rate=engine.synthesize(question);input_pcm=(np.clip(resample_poly(audio,2,3),-1,1)*32767).astype('<i2').tobytes()
        write_wav(out/'voice-question.wav',input_pcm,16000)
        runner=web.AppRunner(make_app(engine,'test-local-voice-token-'+'b'*24));await runner.setup();site=web.TCPSite(runner,'127.0.0.1',0);await site.start();voice_port=site._server.sockets[0].getsockname()[1]
        start=time.monotonic();events=[];chunks=[];synthesis_times=[];first_audio=None;input_finished=None;transcript=None;reply=None
        async with ClientSession() as client:
            ws=await client.ws_connect(f'http://127.0.0.1:{voice_port}/voice',max_msg_size=4*1024**2)
            await ws.send_json({'token':'test-local-voice-token-'+'b'*24});ready=await ws.receive_json();assert ready['type']=='ready'
            async def send_audio():
                nonlocal input_finished
                padded=input_pcm+b'\x00'*(640-len(input_pcm)%640)
                for offset in range(0,len(padded),640):await ws.send_bytes(padded[offset:offset+640]);await asyncio.sleep(.02)
                input_finished=time.monotonic()
                for _ in range(28):await ws.send_bytes(b'\x00'*640);await asyncio.sleep(.02)
            sending=asyncio.create_task(send_audio())
            while True:
                m=await asyncio.wait_for(ws.receive_json(),60);now=time.monotonic()
                events.append({'type':m['type'],'state':m.get('state'),'epoch':m.get('epoch'),'seconds':round(now-start,4)})
                if m['type']=='input_transcript':transcript=m['text']
                if m['type']=='audio':
                    if first_audio is None:first_audio=now
                    chunks.append(base64.b64decode(m['pcm']));synthesis_times.append({'phrase':m['text'],'seconds':m.get('synthesis_seconds')})
                if m['type']=='error':raise RuntimeError(m.get('code'))
                if m['type']=='generation_done':reply=m['text'];break
            await sending
            await ws.send_json({'type':'interrupt'})
            while True:
                m=await asyncio.wait_for(ws.receive_json(),5)
                if m['type']=='interrupt':interrupt_epoch=m['epoch'];break
            stale_after_interrupt=False
            try:
                m=await asyncio.wait_for(ws.receive_json(),.3);stale_after_interrupt=m['type']=='audio' and m['epoch']<interrupt_epoch
            except asyncio.TimeoutError:pass
            await ws.close()
        response_pcm=b''.join(chunks);write_wav(out/'voice-reply.wav',response_pcm,24000)
        result={'status':'REAL_LOCAL_AUDIO_TRANSPORT_PASS','input_source':'synthetic Chinese speech generated by the same local voice model; not independent human microphone evidence',
            'input_question':question,'asr_text':transcript,'reply_text':reply,'audio_chunks':len(chunks),'synthesis_times':synthesis_times,'response_audio_seconds':len(response_pcm)/2/24000,
            'end_of_input_to_first_audio_seconds':round(first_audio-input_finished,3),'stale_audio_after_interrupt':stale_after_interrupt,
            'events':events,'engines':{'asr':'Whisper base / CTranslate2 int8 CPU','chat':'Qwen3-0.6B Q8 CPU','speech':'Kokoro v1.1 zh float32 / zf_001 CPU'},
            'external_ai_api_calls':0,'reads_caption_dom':False,'browser_speech_synthesis':False,'native_speech_foundation_model':False,
            'real_microphone_e2e':'NOT_TESTED','speaker_echo_and_barge_in':'SIMULATED_PROTOCOL_ONLY','ios_safari':'NOT_TESTED','naturalness_listening_review':'NOT_PERFORMED','persistent_public_host':False,
            'artifacts':[{'name':p.name,'bytes':p.stat().st_size,'sha256':hashlib.file_digest(p.open('rb'),'sha256').hexdigest()} for p in [out/'voice-question.wav',out/'voice-reply.wav']]}
        (out/'voice-benchmark.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n');print(json.dumps(result,ensure_ascii=False,indent=2))
    finally:
        if runner:await runner.cleanup()
        shutdown(proc,log)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--model-root',required=True);p.add_argument('--voice-root',required=True);p.add_argument('--output',required=True);asyncio.run(benchmark(p.parse_args()))
